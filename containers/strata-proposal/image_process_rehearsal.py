"""Fixed synthetic image workers in separate processes; no live download bridge.

Only tiny generated bytes and sleeping blocked calls are used. The supervisor
owns the process/job handles and never stops a PID supplied by a caller.
Windows kill-on-close ownership covers supervisor death in the fixed rehearsal;
OS failure and real telemetry/approval admission remain outside this test.
"""
import argparse
import gzip
import hashlib
import io
import json
import math
import os
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import time
import uuid

import image_download as downloads
import image_expand as expand
import windows_job

ROOT = downloads.images.HERE.parents[1] / '.runtime/image-process-rehearsals'
CASES = ('success', 'read-deadline', 'expand-deadline', 'lease-loss', 'cancel', 'gpu-hot', 'owner-death')
ROOT_LIMIT = 32 * 1024**2
RECORD_LIMIT = 4096
SESSION_SECONDS = 6
BLOCK_SECONDS = .4
LEASE_SECONDS = .2


def fixture():
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode='w', format=tarfile.USTAR_FORMAT) as archive:
        entry = tarfile.TarInfo('synthetic.txt')
        payload = b'fixed synthetic image fixture\n'
        entry.size = len(payload)
        archive.addfile(entry, io.BytesIO(payload))
    raw = output.getvalue()
    packed = gzip.compress(raw, mtime=0)
    blob = downloads.Blob('sha256:' + hashlib.sha256(packed).hexdigest(), len(packed))
    return packed, expand.Layer(blob, hashlib.sha256(raw).hexdigest()), len(raw)


def owned(directory):
    directory = Path(directory).absolute()
    downloads.tools.plain(directory)
    if (directory.parents[1] != ROOT or not re.fullmatch('[0-9a-f]{32}', directory.parent.name) or
            directory.name not in CASES):
        raise downloads.StageError('SYNTHETIC_NAMESPACE_INVALID')
    return directory


def read_record(path):
    downloads.tools.plain(path)
    with path.open('rb') as stream:
        raw = stream.read(RECORD_LIMIT + 1)
    if len(raw) > RECORD_LIMIT:
        raise downloads.StageError('REHEARSAL_RECORD_LIMIT')
    return json.loads(raw)


def child(directory):
    directory = owned(directory)
    scenario = directory.name
    payload, spec, _ = fixture()
    limits = downloads.Limits(65536, 1024**2, 0, SESSION_SECONDS, SESSION_SECONDS)
    def guard():
        return not (directory / 'cancel.request').exists()
    def block():
        (directory / 'blocked').write_bytes(b'x')
        time.sleep(30)  # Deliberately ignores same-process cooperative checks.
    class Body(io.BytesIO):
        status = 200
        def getheaders(self):
            return [('Content-Length', str(len(payload)))]
        def read1(self, count):
            if scenario in ('read-deadline', 'lease-loss', 'cancel', 'owner-death'):
                block()
            return super().read(count)
    class Source:
        def open(self, _blob, _context):
            return Body(payload)
    stage = directory / 'stage'
    downloads._stage(stage, (spec.blob,), 'a' * 64, Source(), limits, guard=guard, synthetic=True)
    context = downloads.Context(limits, guard)
    if scenario in ('expand-deadline', 'gpu-hot'):
        # Stall at the input-read boundary of the real expansion kernel.
        real_read = downloads.read_chunk
        def blocked_read(*args, **kwargs):
            block()
            return real_read(*args, **kwargs)
        downloads.read_chunk = blocked_read
    with downloads.tools.base.lock(stage / 'control'):
        result = expand._verify(stage / 'cache', (spec,), expand.Limits(16384, 16384), context)
        downloads.tools.base.atomic(directory / 'worker.json', result)


class Lease:
    """Age is based on local monotonic observation of counter growth, never mtime."""
    def __init__(self, now):
        self.last_clock = self.changed = now
        self.count = 0

    def observe(self, path, now):
        if not math.isfinite(now) or now < self.last_clock:
            raise downloads.StageError('CLOCK_INVALID')
        self.last_clock = now
        downloads.tools.plain(path)
        count = path.stat().st_size if path.exists() else 0
        if count < self.count or count > 256:
            raise downloads.StageError('CONTROLLER_LEASE_INVALID')
        if count > self.count:
            self.changed, self.count = now, count
        if now - self.changed >= LEASE_SECONDS:
            raise downloads.StageError('CONTROLLER_LEASE_LOST')


def stop_child(process):
    """Cooperative cancel file is written by caller before bounded escalation."""
    try:
        try:
            process.wait(timeout=.1)
        except subprocess.TimeoutExpired:
            process.terminate()
            try:
                process.wait(timeout=.7)
            except subprocess.TimeoutExpired:
                process.kill()
                try:
                    process.wait(timeout=.7)
                except subprocess.TimeoutExpired:
                    return False
    except OSError:
        return process.poll() is not None
    return process.poll() is not None


def launch(directory):
    environment = {k: os.environ[k] for k in ('SystemRoot', 'TEMP', 'TMP') if k in os.environ}
    return windows_job.Process([sys.executable, '-B', '-E', '-s', str(Path(__file__).resolve()),
                                '--synthetic-child', str(directory)], cwd=directory, env=environment)


def supervise(directory):
    directory = owned(directory)
    directory.mkdir(exist_ok=True)
    with downloads.tools.base.lock(directory / 'control'):
        state_path = directory / 'state.json'
        if state_path.exists():
            raise downloads.StageError('REHEARSAL_RESTART_REJECTED')
        state = {'version': 1, 'synthetic': True, 'state': 'RUNNING', 'fault': None,
                 'stopConfirmed': False, 'imageDownloadEnabled': False,
                 'imageImportEnabled': False, 'buildEnabled': False, 'modelLaunchEnabled': False}
        downloads.tools.base.atomic(state_path, state)
        process = None
        stop_attempted = False
        failure = None
        try:
            process = launch(directory)
            state['workerPid'] = process.pid  # Diagnostic only; never used to terminate.
            downloads.tools.base.atomic(state_path, state)
            started = last = time.monotonic()
            lease = Lease(started)
            blocked_at = None
            while True:
                now = time.monotonic()
                if not math.isfinite(now) or now < last:
                    raise downloads.StageError('CLOCK_INVALID')
                last = now
                if now - started >= SESSION_SECONDS:
                    raise downloads.StageError('WORKER_DEADLINE')
                blocked = (directory / 'blocked').exists()
                if blocked and blocked_at is None:
                    blocked_at = now
                # Fixed fake controller; no real CPU/GPU sensor is read.
                if directory.name != 'lease-loss' or not blocked:
                    with (directory / 'controller.pulse').open('ab') as pulse:
                        pulse.write(b'x')
                lease.observe(directory / 'controller.pulse', now)
                if blocked_at is not None:
                    age = now - blocked_at
                    if directory.name == 'gpu-hot' and age >= .1:
                        raise downloads.StageError('SYNTHETIC_GPU_HOT')
                    if directory.name == 'cancel' and age >= .1:
                        raise downloads.StageError('CANCELLED')
                    if age >= BLOCK_SECONDS:
                        raise downloads.StageError('WORKER_PROGRESS_DEADLINE')
                if process.poll() is not None:
                    if process.returncode != 0:
                        raise downloads.StageError('WORKER_EXIT_FAILED')
                    result = read_record(directory / 'worker.json')
                    _, spec, size = fixture()
                    expected = {'status': 'STREAMS_VERIFIED_NOT_IMPORTED', 'layers': [{
                        'digest': spec.blob.digest, 'compressedBytes': spec.blob.size,
                        'expandedBytes': size, 'expandedSha256': spec.expanded_sha256}],
                        'expandedBytes': size, 'extracted': False, 'dockerDiskUsageBounded': False}
                    if result != expected:
                        raise downloads.StageError('WORKER_RESULT_INVALID')
                    state.update(state='COMPLETE', stopConfirmed=True, result=result)
                    break
                time.sleep(.025)
        except BaseException as error:
            failure = error
            fault_at = time.monotonic()
            state.update(state='FAULT', fault=error.code if isinstance(error, downloads.StageError) else 'SUPERVISOR_ERROR')
            try:
                downloads.tools.base.atomic(state_path, state)  # Latch before stopping.
            finally:
                if process is not None:
                    try:
                        (directory / 'cancel.request').write_bytes(b'x')
                    finally:
                        stop_attempted = True
                        state['stopConfirmed'] = stop_child(process)
                        state['stopElapsedSeconds'] = time.monotonic() - fault_at
        finally:
            # An I/O error while recording state still takes the stop path.
            if process is not None and process.poll() is None:
                state.update(state='FAULT', fault=state['fault'] or 'UNFINISHED_WORKER')
                # Do not reset the stop budget or hide an unconfirmed attempt
                # behind a second termination sequence.
                state['stopConfirmed'] = False if stop_attempted else stop_child(process)
            try:
                downloads.tools.base.atomic(state_path, state)
            finally:
                if process is not None:
                    process.close()  # Kill-on-close also covers unconfirmed exit.
        if failure is not None and not isinstance(failure, downloads.StageError):
            raise failure
        return state


def orphan_owner(directory):
    directory = owned(directory)
    if directory.name != 'owner-death':
        raise downloads.StageError('SYNTHETIC_NAMESPACE_INVALID')
    directory.mkdir(exist_ok=True)
    downloads.tools.base.atomic(directory / 'state.json', {'state': 'RUNNING', 'synthetic': True})
    with launch(directory) as worker:
        downloads.tools.base.atomic(directory / 'owner.ready.json', {'witness': worker.witness_for_parent()})
        time.sleep(30)


def verify_owner_death(directory):
    directory = owned(directory)
    directory.mkdir()
    owner = witness = None
    try:
        owner = subprocess.Popen([sys.executable, '-B', '-E', '-s', str(Path(__file__).resolve()),
                                  '--orphan-owner', str(directory)], stdin=subprocess.DEVNULL,
                                 stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                 creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
        end = time.monotonic() + SESSION_SECONDS
        while time.monotonic() < end:
            if (directory / 'owner.ready.json').exists() and (directory / 'blocked').exists():
                break
            if owner.poll() is not None:
                raise AssertionError('Synthetic owner failed before lifetime test')
            time.sleep(.025)
        else:
            raise TimeoutError('Synthetic owner setup deadline')
        witness = windows_job.Witness(read_record(directory / 'owner.ready.json')['witness'])
        if witness.poll() is not None:
            raise AssertionError('Worker not alive before killing synthetic owner')
        started = time.monotonic()
        owner.kill()  # Abrupt death: owner finally/cleanup code cannot run.
        owner.wait(timeout=2)
        witness.wait(timeout=2)
        elapsed = time.monotonic() - started
        # An unfinished RUNNING journal must deny restart even before a verifier
        # records the death. Death itself cannot promise a new durable FAULT.
        try:
            supervise(directory)
        except downloads.StageError as error:
            if error.code != 'REHEARSAL_RESTART_REJECTED':
                raise
        else:
            raise AssertionError('Unfinished owner session restarted')
        state = {'version': 1, 'synthetic': True, 'state': 'FAULT', 'fault': 'SUPERVISOR_EXIT',
                 'stopConfirmed': True, 'stopElapsedSeconds': elapsed, 'restartRejected': True,
                 'ownership': 'windows-job-kill-on-close', 'imageDownloadEnabled': False,
                 'imageImportEnabled': False, 'buildEnabled': False, 'modelLaunchEnabled': False}
        downloads.tools.base.atomic(directory / 'state.json', state)
        return state
    finally:
        if owner is not None and owner.poll() is None:
            owner.kill()
            owner.wait(timeout=2)
        if witness is not None:
            witness.wait(timeout=2)
            witness.close()


def verify():
    downloads.tools.plain(ROOT)
    with downloads.tools.base.lock(ROOT / 'control'):
        entries, used = downloads.plain_usage(ROOT)
        if entries + 150 > downloads.ENTRY_LIMIT or used + 4 * 1024**2 > ROOT_LIMIT:
            raise downloads.StageError('REHEARSAL_NAMESPACE_FULL')
        directory = ROOT / uuid.uuid4().hex
        directory.mkdir()
        result = {'version': 1, 'passed': False, 'synthetic': True, 'networkUsed': False,
                  'dockerUsed': False, 'realImageLayersDecompressed': False,
                  'modelStarted': False, 'compilerStarted': False, 'cases': []}
        expected_faults = dict(zip(CASES[1:], ('WORKER_PROGRESS_DEADLINE', 'WORKER_PROGRESS_DEADLINE',
                                               'CONTROLLER_LEASE_LOST', 'CANCELLED', 'SYNTHETIC_GPU_HOT')))
        try:
            for scenario in CASES:
                if scenario == 'owner-death':
                    state = verify_owner_death(directory / scenario)
                    result['cases'].append({'scenario': scenario, **state})
                    continue
                state = supervise(directory / scenario)
                if not state['stopConfirmed'] or state['fault'] != expected_faults.get(scenario):
                    raise AssertionError('Unexpected synthetic worker result')
                if scenario != 'success' and state['stopElapsedSeconds'] > 2:
                    raise AssertionError('Synthetic worker stopping exceeded bound')
                try:
                    supervise(directory / scenario)
                except downloads.StageError as error:
                    if error.code != 'REHEARSAL_RESTART_REJECTED':
                        raise
                else:
                    raise AssertionError('Session incorrectly restarted')
                result['cases'].append({'scenario': scenario, **state, 'restartRejected': True})
            result['passed'] = True
        finally:
            downloads.tools.base.atomic(directory / 'result.json', result)
        print(json.dumps({'directory': str(directory), **result}, indent=2))
        return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--execute-synthetic-only', action='store_true')
    mode.add_argument('--synthetic-child')
    mode.add_argument('--orphan-owner')
    options = parser.parse_args()
    if options.synthetic_child:
        child(options.synthetic_child)
    elif options.orphan_owner:
        orphan_owner(options.orphan_owner)
    else:
        verify()
